#!/usr/bin/env python3
"""Generate and check the supported Linux x86_64 distribution byte locks.

Generation downloads wheels only, never executes package code, and keeps every
existing version/marker. pip check in each native CI interpreter qualifies the
closure separately; cross-interpreter download is not an execution test.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSIONS = ("3.11", "3.12", "3.13")
PLATFORMS = (
    "manylinux_2_28_x86_64",
    "manylinux_2_27_x86_64",
    "manylinux2014_x86_64",
    "manylinux_2_17_x86_64",
)
MANIFEST = ROOT / "locks/wheels-linux-x86_64.json"


def pins(path: Path) -> list[str]:
    result = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "--hash=")):
            continue
        line = line.removesuffix("\\").strip()
        if line.startswith("-r "):
            continue
        if not re.fullmatch(
            r"[\w.-]+==[\w.+-]+(?: ; python_version [<>]=? \"3\.\d+\")?", line
        ):
            raise ValueError(f"Unsupported lock syntax: {line}")
        result.append(line)
    return result


def applies(pin: str, version: str) -> bool:
    if " ; " not in pin:
        return True
    marker = pin.split(" ; ")[1]
    target = tuple(map(int, marker.split('"')[1].split(".")))
    actual = tuple(map(int, version.split(".")))
    return actual >= target if ">=" in marker else actual < target


def distribution(pin: str) -> tuple[str, str]:
    name, version = pin.split(" ; ")[0].split("==")
    return re.sub(r"[-_.]+", "-", name).lower(), version


def digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def generate() -> None:
    files = (
        "requirements.lock",
        "requirements-dev.lock",
        "requirements-bootstrap.lock",
    )
    groups = {name: pins(ROOT / name) for name in files}
    all_pins = [pin for group in groups.values() for pin in group]
    hashes: dict[tuple[str, str], set[str]] = {}
    wheels: dict[str, dict] = {}
    with tempfile.TemporaryDirectory(prefix="itd-hash-lock-") as directory:
        for version in VERSIONS:
            active = sorted(
                {pin.split(" ; ")[0] for pin in all_pins if applies(pin, version)}
            )
            target = Path(directory) / version
            command = [
                sys.executable,
                "-m",
                "pip",
                "download",
                "--only-binary=:all:",
                "--no-deps",
                "--python-version",
                version,
                "--implementation",
                "cp",
                "--abi",
                "cp" + version.replace(".", ""),
                "--dest",
                str(target),
            ]
            for platform in PLATFORMS:
                command.extend(("--platform", platform))
            subprocess.run(command + active, check=True)
            downloaded = list(target.glob("*.whl"))
            if len(downloaded) != len(active):
                raise ValueError("Incomplete wheel closure")
            for wheel in downloaded:
                parts = wheel.name.split("-")
                key = (re.sub(r"[-_.]+", "-", parts[0]).lower(), parts[1])
                sha = digest(wheel)
                hashes.setdefault(key, set()).add(sha)
                row = wheels.setdefault(
                    wheel.name,
                    {
                        "filename": wheel.name,
                        "distribution": key[0],
                        "version": key[1],
                        "sha256": sha,
                        "size_bytes": wheel.stat().st_size,
                        "python_versions": [],
                    },
                )
                if row["sha256"] != sha:
                    raise ValueError("Wheel bytes changed during generation")
                row["python_versions"].append(version)
    for name, group in groups.items():
        text = [
            "# Generated by tools/lock_wheels.py; CPython 3.11-3.13, Linux x86_64.",
            "# Wheels only; install with --require-hashes --only-binary=:all:.",
        ]
        if name == "requirements-dev.lock":
            text.append("-r requirements.lock")
            text.append("-r requirements-bootstrap.lock")
        for pin in group:
            values = sorted(hashes[distribution(pin)])
            text.append(pin + " \\")
            text.extend(
                "    --hash=sha256:" + value + (" \\" if i + 1 < len(values) else "")
                for i, value in enumerate(values)
            )
        (ROOT / name).write_text("\n".join(text) + "\n")
    MANIFEST.parent.mkdir(exist_ok=True)
    MANIFEST.write_text(
        json.dumps(
            {
                "schema": "itd-wheel-lock.v1",
                "platforms": PLATFORMS,
                "python_versions": VERSIONS,
                "wheels": [wheels[name] for name in sorted(wheels)],
            },
            indent=2,
            sort_keys=True,
        )
        + "\n"
    )


def verify(directory: Path, version: str) -> None:
    manifest = json.loads(MANIFEST.read_text())
    expected = {
        row["filename"]: row
        for row in manifest["wheels"]
        if version in row["python_versions"]
    }
    actual = {path.name: path for path in directory.iterdir()}
    if actual.keys() != expected.keys():
        raise ValueError(f"Wheel inventory mismatch: {actual.keys() ^ expected.keys()}")
    for name, path in actual.items():
        row = expected[name]
        if (
            not path.is_file()
            or path.is_symlink()
            or path.stat().st_size != row["size_bytes"]
            or digest(path) != row["sha256"]
        ):
            raise ValueError(f"Wheel integrity mismatch: {name}")
    print(f"Verified {len(actual)} distribution byte identities for CPython {version}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate", action="store_true")
    parser.add_argument("--verify", type=Path)
    parser.add_argument(
        "--python-version",
        choices=VERSIONS,
        default=f"{sys.version_info.major}.{sys.version_info.minor}",
    )
    arguments = parser.parse_args()
    if arguments.generate == (arguments.verify is not None):
        parser.error("choose exactly one of --generate or --verify DIRECTORY")
    if arguments.generate:
        generate()
    else:
        verify(arguments.verify, arguments.python_version)


if __name__ == "__main__":
    main()
